    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        try {
            String nombreAPP = campoNombreApp.getText();
            String ip = campoIP.getText();
            String puerto = campoPuerto.getText().trim();
            String usuario = campoUsuario.getText();
            String pass = campoPass.getText();

            if(nombreAPP.isEmpty() || ip.isEmpty() || puerto.isEmpty() || usuario.isEmpty() || pass.isEmpty()) {

                JOptionPane.showMessageDialog(this, "Faltan datos por rellenar");
                return;

            }

            Configuracion conf = new Configuracion(nombreAPP,ip,Integer.parseInt(puerto),usuario,pass);
            ProyectoFinal.BaseDeDatos.ConexionBBDD.Inicializar(conf);

            try (java.sql.Connection testCon = ProyectoFinal.BaseDeDatos.ConexionBBDD.getConexion()) {

                GestorConfiguracion gestor = GestorConfiguracion.getInstance();
                gestor.guardarConfiguracion(conf);

                this.dispose();

                Starter.abrirPantallaPrincipal(conf);

            } catch (java.sql.SQLException e) {

                JOptionPane.showMessageDialog(this,  "No se pudo conectar a la Base de Datos con esos datos.\nError: " + e.getMessage(),
                    "Error de Conexión (Acceso Denegado)",  JOptionPane.ERROR_MESSAGE);
            }

            // TODO add your handling code here:
        } catch (Exception ex) {
            System.getLogger(JConfiguracion.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

