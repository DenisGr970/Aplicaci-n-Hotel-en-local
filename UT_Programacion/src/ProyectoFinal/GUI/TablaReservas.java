    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed

        int filaSel = jTable1.getSelectedRow();

        if (filaSel == -1) {

            JOptionPane.showMessageDialog(this, "Por favor, selecciona una reserva de la lista para modificar");
            return;

        }
        int idReserva = (int) jTable1.getValueAt(filaSel, 0);
        String entradaActual = jTable1.getValueAt(filaSel, 2).toString();
        String salidaActual = jTable1.getValueAt(filaSel, 3).toString();
        String personasActual = jTable1.getValueAt(filaSel, 4).toString();
        String habitacionActual = jTable1.getValueAt(filaSel, 5).toString();

        com.toedter.calendar.JDateChooser jdEntrada = new com.toedter.calendar.JDateChooser();
        com.toedter.calendar.JDateChooser jdSalida = new com.toedter.calendar.JDateChooser();

        String[] opcionesPersonas = {"1 Persona", "2 Personas", "3 Personas", "4 Personas"};
        JComboBox<String> comboPersonas = new JComboBox<>(opcionesPersonas);
        comboPersonas.setSelectedItem(personasActual);

        String[] tiposHabitacion = {"Simple", "Doble", "Suite"};
        JComboBox<String> comboHabitacion = new javax.swing.JComboBox<>(tiposHabitacion);
        comboHabitacion.setSelectedItem(habitacionActual);

        try {
            java.util.Date fechaEnt = java.sql.Date.valueOf(entradaActual);
            java.util.Date fechaSal = java.sql.Date.valueOf(salidaActual);
            jdEntrada.setDate(fechaEnt);
            jdSalida.setDate(fechaSal);

            jdEntrada.setDateFormatString("yyyy-MM-dd");
            jdSalida.setDateFormatString("yyyy-MM-dd");
        } catch (Exception e) {
            System.out.println("Error al cargar fechas en los calendarios: " + e.getMessage());
        }

        JPanel panelEdicion = new JPanel();
        panelEdicion.setLayout(new java.awt.GridLayout(4, 2, 5, 5));

        panelEdicion.add(new JLabel("Fecha Entrada:"));
        panelEdicion.add(jdEntrada);

        panelEdicion.add(new JLabel("Fecha Salida:"));
        panelEdicion.add(jdSalida);

        panelEdicion.add(new JLabel("Número de Personas:"));
        panelEdicion.add(comboPersonas);

        panelEdicion.add(new JLabel("Tipo de Habitación:"));
        panelEdicion.add(comboHabitacion);

        int opcion = JOptionPane.showConfirmDialog(this, panelEdicion,
                "Modificar Reserva Nº " + idReserva, JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);

        if (opcion == JOptionPane.OK_OPTION) {
            try {
                if (jdEntrada.getDate() == null || jdSalida.getDate() == null) {
                    JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                java.util.Date fEntrada = jdEntrada.getDate();
                java.util.Date fSalida = jdSalida.getDate();

                long difMilis = fSalida.getTime() - fEntrada.getTime();
                long dias = difMilis / (1000 * 60 * 60 * 24);

                if (dias <= 0) {
                    JOptionPane.showMessageDialog(this, "La fecha de salida debe ser posterior a la de entrada.", "Error de fechas", JOptionPane.ERROR_MESSAGE);
                    return;
                }

                String nuevoTipoHab = comboHabitacion.getSelectedItem().toString();
                double precioNoche = 0.0;
                if (nuevoTipoHab.equals("Simple")) {
                    precioNoche = 50.0;
                } else if (nuevoTipoHab.equals("Doble")) {
                    precioNoche = 70.0;
                } else if (nuevoTipoHab.equals("Suite")) {
                    precioNoche = 100.0;
                }

                double nuevoPrecioTotal = dias * precioNoche;

                java.sql.Date nuevaEntrada = new java.sql.Date(fEntrada.getTime());
                java.sql.Date nuevaSalida = new java.sql.Date(fSalida.getTime());

                String numPersonas = comboPersonas.getSelectedItem().toString();

                UsuarioDAO dao = new UsuarioDAO();
                boolean exito = dao.modificarReserva(idReserva, nuevaEntrada, nuevaSalida, numPersonas, nuevoTipoHab, nuevoPrecioTotal);

                if (exito) {
                    JOptionPane.showMessageDialog(this, "Reserva modificada correctamente.");
                    cargarDatosTabla();
                } else {
                    JOptionPane.showMessageDialog(this, "Error al guardar las modificaciones en la Base de Datos.");
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al procesar los datos: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnModificarActionPerformed

