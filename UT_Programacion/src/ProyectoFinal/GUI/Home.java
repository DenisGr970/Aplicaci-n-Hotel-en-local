    private void actualizarPrecio() {
        
        java.util.Date fechaEnt = fEntrada.getDate();
    java.util.Date fechaSal = fSalida.getDate();
    
    if (fechaEnt == null || fechaSal == null) {
        lblPrecioTotal.setText("Precio total: -- €");
        return;
    }
    
    long difMilis = fechaSal.getTime() - fechaEnt.getTime();
    long dias = difMilis / (1000 * 60 * 60 * 24);
    
    if (dias <= 0) {
        lblPrecioTotal.setText("Fecha de salida inválida");
        return;
    }
    
    String seleccion = SeleccionHabitacion.getSelectedItem().toString();
    double precioNoche = 0.0;
    
    if (seleccion.contains("Habitación Simple")) {
        precioNoche = 50.0;
    } else if (seleccion.contains("Habitación Doble")) {
        precioNoche = 70.0;
    } else if (seleccion.contains("Habitación Suite")) {
        precioNoche = 100.0;
    }
    
 double precioTotalCalculado = dias * precioNoche;
    lblPrecioTotal.setText("Precio total: " + precioTotalCalculado + " € (" + dias + " noches)");
}
    
    
    
    
    
    
