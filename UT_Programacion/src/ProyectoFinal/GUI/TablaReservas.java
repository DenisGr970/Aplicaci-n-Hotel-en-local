    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSel = jTable1.getSelectedRow();

        if (filaSel == -1) {

            JOptionPane.showMessageDialog(this, "Por favor, selecciona una reserva de la lista para eliminar");
            return;

        }

        int idReserva = (int) jTable1.getValueAt(filaSel, 0);

        int respuesta = JOptionPane.showConfirmDialog(this, "Seguro que desea eliminar la reserva Nº " + idReserva + ".\n¿Proceder? ", "Eliminar Reserva", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (respuesta == JOptionPane.YES_OPTION) {

            UsuarioDAO dao = new UsuarioDAO();
            if (dao.eliminarReserva(idReserva)) {
                JOptionPane.showMessageDialog(this, "Reserva eliminada con éxito");
                cargarDatosTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar la reserva");
            }

        }

    }//GEN-LAST:event_btnEliminarActionPerformed

