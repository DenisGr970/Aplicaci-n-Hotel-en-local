    private void btnReservarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReservarActionPerformed

        String seleccion = SeleccionHabitacion.getSelectedItem().toString();
        Habitacion hab = null;
        ArrayList<String> fotosVacias = new ArrayList<>();
        String extras ="";

       if (seleccion.contains("Simple")) {
            hab = new HabitacionSimple(1, 50.0, fotosVacias);
        } else if (seleccion.contains("Doble")) {
            hab = new HabitacionDoble(2, 70.0, fotosVacias);
        } else if(seleccion.contains("Suite")) {
            Suite miSuite  = new Suite(3, 100.0, fotosVacias, true, 20.0, true);
           hab = miSuite;
           extras = "\n  · Incluye Jacuzzi: " + (miSuite.isJacuzzi() ? "Sí" : "No")
           + "\n  · Incluye Minibar: " + (miSuite.isMinibar() ? "Sí" : "No")
           + "\n  · Terraza: " + miSuite.getMetrosterraza() + " metros cuadrados";

        }

        java.util.Date fechaEntrada = fEntrada.getDate();
        java.util.Date fechaSalida = fSalida.getDate();
        java.util.Date fechaHoy = new java.util.Date();

        if (fechaEntrada == null || fechaSalida == null) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione ambas fechas.", "Error", JOptionPane.WARNING_MESSAGE);
            fEntrada.setCalendar(null);
            fSalida.setCalendar(null);
            return;
        }
        if (fechaEntrada.before(fechaHoy)) {

            JOptionPane.showMessageDialog(this, "No puede reservar en una fecha que ya ha pasado", "Fecha no válida", JOptionPane.WARNING_MESSAGE);
            fEntrada.setCalendar(null);
            fSalida.setCalendar(null);
            return;
        }

        if (!fechaSalida.after(fechaEntrada)) {

            JOptionPane.showMessageDialog(this, "La fecha de salida debe ser posterior a la de entrada", "Error en las fechas", JOptionPane.WARNING_MESSAGE);
            fEntrada.setCalendar(null);
            fSalida.setCalendar(null);
            return;
            
            
           

        }
        
        int HabitacionesOcupadas = 0;
        
        java.sql.Date sqlEntrada = new java.sql.Date(fechaEntrada.getTime());
        java.sql.Date sqlSalida = new java.sql.Date(fechaSalida.getTime());
        
        String sqlContar = "SELECT COUNT(*) FROM reservas WHERE tipo = ? AND "
                     + "((fecha_entrada >= ? AND fecha_entrada < ?) OR (fecha_salida > ? AND fecha_salida <= ?) OR (fecha_entrada <= ? AND fecha_salida >= ?))";
        
        try (java.sql.Connection conn = ProyectoFinal.BaseDeDatos.ConexionBBDD.getConexion();
         java.sql.PreparedStatement ps = conn.prepareStatement(sqlContar)) {
        
        ps.setString(1, seleccion); 
        ps.setDate(2, sqlEntrada);
        ps.setDate(3, sqlSalida);
        ps.setDate(4, sqlEntrada);
        ps.setDate(5, sqlSalida);
        ps.setDate(6, sqlEntrada);
        ps.setDate(7, sqlSalida);
        
        try (java.sql.ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                HabitacionesOcupadas = rs.getInt(1); 
            }
        }
    } catch (java.sql.SQLException e) {
        System.out.println("Error al comprobar la disponibilidad: " + e.getMessage());
    }


    if (HabitacionesOcupadas >= 10) {
        JOptionPane.showMessageDialog(this, 
            "¡Lo sentímos, ya no hay habitaciones disponibles del tipo '" + seleccion + "' para las fechas seleccionadas!\nActualmente hay " + HabitacionesOcupadas + " ocupadas de 10 disponibles.", 
            "Hotel Completo", 
            JOptionPane.ERROR_MESSAGE);
        return;
    }

        

        long diferenciaEnMilis = Math.abs(fechaSalida.getTime() - fechaEntrada.getTime());
        long dias = diferenciaEnMilis / (1000 * 60 * 60 * 24);
        
        
        double precioPorNoche = hab.getPrecioBase();
double precioTotalCalculado = dias * precioPorNoche;


 
String resumenMsg = "Resumen de tu estancia:\n"
            + "· Tipo: " + seleccion + "\n"
            + "· Duración: " + dias + " noches\n"
            + "· Precio por noche: " + precioPorNoche + " €\n"
            + extras  + "\n"
            + "=======================\n"
            + "PRECIO TOTAL ESTIMADO: " + precioTotalCalculado + " €\n\n"
            + "¿Estás seguro de que deseas confirmar la reserva?";
            
    int confirmar = JOptionPane.showConfirmDialog(this, resumenMsg, "Confirmar Importe de Reserva", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        
    if (confirmar == JOptionPane.YES_OPTION) {
        UsuarioDAO dao = new UsuarioDAO();
        
    

        if (dao.guardarReserva(this.IDusuarioLogueado,this.nombreUsuario, fechaEntrada, fechaSalida, SeleccionPersonas.getSelectedItem().toString(), SeleccionHabitacion.getSelectedItem().toString(),precioTotalCalculado)) {
            String mensaje = ("Reserva confirmada para: " + this.nombreUsuario + "\nCoste total de la estancia: " + precioTotalCalculado + "€ ");
            JOptionPane.showMessageDialog(this, mensaje, "Reserva guardada con éxito en nuestra base de datos!", JOptionPane.INFORMATION_MESSAGE);
            fEntrada.setCalendar(null);
            fSalida.setCalendar(null);
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar la reserva en nuestra base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    }//GEN-LAST:event_btnReservarActionPerformed

