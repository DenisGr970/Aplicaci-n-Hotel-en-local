    public void cargarValores() {
        try {
        GestorConfiguracion gestor = GestorConfiguracion.getInstance();
        Configuracion conf = gestor.cargarConfiguracion();
        
        if(conf != null) {
        
        campoNombreApp.setText(conf.getNombreApp());
        campoIP.setText(conf.getIp_bbdd());
        campoPuerto.setText(conf.getPuerto_bbdd() + "");
        campoUsuario.setText(conf.getUsuario_bbdd());
        campoPass.setText(conf.getContrasena_bbdd());
        }
        }catch(Exception e) {
            System.out.println("ERROR al cargar valores: " + e.getMessage());
        }
    }

